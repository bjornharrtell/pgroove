//! Table structure: columns, constraints, indexes, triggers, size, and DDL.

use anyhow::{Result, anyhow};
use tokio_postgres::Client;

use crate::catalog::ObjectKind;
use crate::data::{TableRef, quote_ident};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ColumnInfo {
    pub name: String,
    pub data_type: String,
    pub not_null: bool,
    pub default: Option<String>,
    /// `a` (always) or `d` (by default) for identity columns.
    pub identity: Option<char>,
    pub generated: bool,
    pub comment: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConstraintInfo {
    pub name: String,
    /// `p`, `u`, `f`, `c` or `x`.
    pub kind: char,
    pub definition: String,
    /// Referenced table for foreign keys.
    pub references: Option<TableRef>,
    /// Columns the constraint covers, in constraint order, for the constraint kinds
    /// that name a key; a check lists the columns it looks at, an exclusion constraint
    /// records none.
    pub columns: Vec<String>,
}

impl ConstraintInfo {
    pub fn kind_label(&self) -> &'static str {
        match self.kind {
            'p' => "primary key",
            'u' => "unique",
            'f' => "foreign key",
            'c' => "check",
            'x' => "exclusion",
            _ => "other",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IndexInfo {
    pub name: String,
    pub definition: String,
    pub unique: bool,
    pub primary: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TriggerInfo {
    pub name: String,
    pub definition: String,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct Stats {
    pub table_bytes: u64,
    pub index_bytes: u64,
    pub total_bytes: u64,
    /// Planner estimate; negative when never analyzed.
    pub estimated_rows: f64,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Structure {
    pub kind: ObjectKind,
    pub columns: Vec<ColumnInfo>,
    pub constraints: Vec<ConstraintInfo>,
    pub indexes: Vec<IndexInfo>,
    pub triggers: Vec<TriggerInfo>,
    pub stats: Stats,
    /// Query text for views and materialized views.
    pub view_definition: Option<String>,
}

pub fn format_bytes(b: u64) -> String {
    const UNITS: [&str; 5] = ["B", "KiB", "MiB", "GiB", "TiB"];
    let mut v = b as f64;
    let mut u = 0;
    while v >= 1024. && u < UNITS.len() - 1 {
        v /= 1024.;
        u += 1;
    }
    if u == 0 {
        format!("{b} B")
    } else {
        format!("{v:.1} {}", UNITS[u])
    }
}

pub fn format_rows(estimate: f64) -> String {
    if estimate < 0. {
        "not analyzed".into()
    } else {
        format!("~{}", estimate.round() as u64)
    }
}

fn column_line(c: &ColumnInfo) -> String {
    let mut s = format!("{} {}", quote_ident(&c.name), c.data_type);
    match (c.identity, c.generated, &c.default) {
        (Some('a'), _, _) => s.push_str(" generated always as identity"),
        (Some(_), _, _) => s.push_str(" generated by default as identity"),
        (None, true, Some(e)) => s.push_str(&format!(" generated always as ({e}) stored")),
        (None, false, Some(d)) => s.push_str(&format!(" default {d}")),
        _ => {}
    }
    if c.not_null {
        s.push_str(" not null");
    }
    s
}

/// Reconstructs creation SQL from the loaded structure.
pub fn ddl(table: &TableRef, st: &Structure) -> String {
    if let Some(def) = &st.view_definition {
        let kw = if st.kind == ObjectKind::MaterializedView {
            "materialized view"
        } else {
            "view"
        };
        return format!("create {kw} {} as\n{}\n", table.qualified(), def.trim_end());
    }
    let mut lines: Vec<String> = st
        .columns
        .iter()
        .map(|c| format!("    {}", column_line(c)))
        .collect();
    lines.extend(
        st.constraints
            .iter()
            .map(|c| format!("    constraint {} {}", quote_ident(&c.name), c.definition)),
    );
    let mut out = format!(
        "create table {} (\n{}\n);\n",
        table.qualified(),
        lines.join(",\n")
    );
    for idx in &st.indexes {
        if st.constraints.iter().any(|c| c.name == idx.name) {
            continue;
        }
        out.push_str(&format!("{};\n", idx.definition));
    }
    for t in &st.triggers {
        out.push_str(&format!("{};\n", t.definition));
    }
    out
}

pub async fn load(client: &Client, table: &TableRef) -> Result<Structure> {
    let row = client
        .query_opt(
            "select c.oid, c.relkind::text from pg_class c \
             join pg_namespace n on n.oid = c.relnamespace \
             where n.nspname = $1 and c.relname = $2",
            &[&table.schema, &table.name],
        )
        .await?
        .ok_or_else(|| anyhow!("{} no longer exists", table.qualified()))?;
    let oid: u32 = row.get(0);
    let kind = ObjectKind::from_relkind(row.get::<_, &str>(1))
        .ok_or_else(|| anyhow!("unsupported relation kind"))?;

    let columns = client
        .query(
            "select a.attname::text, format_type(a.atttypid, a.atttypmod), a.attnotnull, \
                    pg_get_expr(d.adbin, d.adrelid), a.attidentity::text, \
                    a.attgenerated::text, col_description(a.attrelid, a.attnum) \
             from pg_attribute a \
             left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum \
             where a.attrelid = $1 and a.attnum > 0 and not a.attisdropped \
             order by a.attnum",
            &[&oid],
        )
        .await?
        .iter()
        .map(|r| ColumnInfo {
            name: r.get(0),
            data_type: r.get(1),
            not_null: r.get(2),
            default: r.get(3),
            identity: r.get::<_, String>(4).chars().next(),
            generated: !r.get::<_, String>(5).is_empty(),
            comment: r.get(6),
        })
        .collect();

    let constraints = client
        .query(
            "select con.conname::text, con.contype::text, pg_get_constraintdef(con.oid), \
                    rn.nspname::text, rc.relname::text, \
                    coalesce((select array_agg(a.attname::text order by k.ord)
                              from unnest(con.conkey) with ordinality as k(attnum, ord)
                              join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.attnum),
                             '{}') \
             from pg_constraint con \
             left join pg_class rc on rc.oid = con.confrelid \
             left join pg_namespace rn on rn.oid = rc.relnamespace \
             where con.conrelid = $1 and con.contype in ('p','u','f','c','x') \
             order by con.contype, con.conname",
            &[&oid],
        )
        .await?
        .iter()
        .map(|r| ConstraintInfo {
            name: r.get(0),
            kind: r.get::<_, String>(1).chars().next().unwrap_or('?'),
            definition: r.get(2),
            references: match (r.get::<_, Option<String>>(3), r.get::<_, Option<String>>(4)) {
                (Some(s), Some(n)) => Some(TableRef::new(s, n)),
                _ => None,
            },
            columns: r.get(5),
        })
        .collect();

    let indexes = client
        .query(
            "select ic.relname::text, pg_get_indexdef(i.indexrelid), i.indisunique, i.indisprimary \
             from pg_index i join pg_class ic on ic.oid = i.indexrelid \
             where i.indrelid = $1 order by 1",
            &[&oid],
        )
        .await?
        .iter()
        .map(|r| IndexInfo {
            name: r.get(0),
            definition: r.get(1),
            unique: r.get(2),
            primary: r.get(3),
        })
        .collect();

    let triggers = client
        .query(
            "select tgname::text, pg_get_triggerdef(oid) from pg_trigger \
             where tgrelid = $1 and not tgisinternal order by 1",
            &[&oid],
        )
        .await?
        .iter()
        .map(|r| TriggerInfo {
            name: r.get(0),
            definition: r.get(1),
        })
        .collect();

    let s = client
        .query_one(
            "select pg_table_size($1::oid)::int8, pg_indexes_size($1::oid)::int8, \
                    pg_total_relation_size($1::oid)::int8, \
                    (select reltuples::float8 from pg_class where oid = $1)",
            &[&oid],
        )
        .await?;
    let stats = Stats {
        table_bytes: s.get::<_, i64>(0).max(0) as u64,
        index_bytes: s.get::<_, i64>(1).max(0) as u64,
        total_bytes: s.get::<_, i64>(2).max(0) as u64,
        estimated_rows: s.get(3),
    };

    let view_definition = if matches!(kind, ObjectKind::View | ObjectKind::MaterializedView) {
        client
            .query_one("select pg_get_viewdef($1::oid, true)", &[&oid])
            .await?
            .get(0)
    } else {
        None
    };

    Ok(Structure {
        kind,
        columns,
        constraints,
        indexes,
        triggers,
        stats,
        view_definition,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(name: &str, ty: &str) -> ColumnInfo {
        ColumnInfo {
            name: name.into(),
            data_type: ty.into(),
            not_null: false,
            default: None,
            identity: None,
            generated: false,
            comment: None,
        }
    }

    fn empty(kind: ObjectKind) -> Structure {
        Structure {
            kind,
            columns: vec![],
            constraints: vec![],
            indexes: vec![],
            triggers: vec![],
            stats: Stats::default(),
            view_definition: None,
        }
    }

    #[test]
    fn byte_and_row_formatting() {
        assert_eq!(format_bytes(512), "512 B");
        assert_eq!(format_bytes(8192), "8.0 KiB");
        assert_eq!(format_bytes(5 * 1024 * 1024 + 512 * 1024), "5.5 MiB");
        assert_eq!(format_rows(-1.), "not analyzed");
        assert_eq!(format_rows(1234.4), "~1234");
    }

    #[test]
    fn kind_labels() {
        for (k, l) in [
            ('p', "primary key"),
            ('u', "unique"),
            ('f', "foreign key"),
            ('c', "check"),
            ('x', "exclusion"),
            ('z', "other"),
        ] {
            let c = ConstraintInfo {
                name: "n".into(),
                kind: k,
                definition: String::new(),
                references: None,
                columns: vec![],
            };
            assert_eq!(c.kind_label(), l);
        }
    }

    #[test]
    fn table_ddl() {
        let t = TableRef::new("public", "orders");
        let mut st = empty(ObjectKind::Table);
        let mut id = col("id", "integer");
        id.identity = Some('a');
        id.not_null = true;
        let mut status = col("status", "text");
        status.default = Some("'new'::text".into());
        let mut total = col("total2", "numeric");
        total.generated = true;
        total.default = Some("(total * 2)".into());
        let mut by_default = col("n", "integer");
        by_default.identity = Some('d');
        st.columns = vec![id, status, total, by_default];
        st.constraints = vec![ConstraintInfo {
            name: "orders_pkey".into(),
            kind: 'p',
            definition: "PRIMARY KEY (id)".into(),
            references: None,
            columns: vec!["id".into()],
        }];
        st.indexes = vec![
            IndexInfo {
                name: "orders_pkey".into(),
                definition: "CREATE UNIQUE INDEX orders_pkey ON public.orders (id)".into(),
                unique: true,
                primary: true,
            },
            IndexInfo {
                name: "orders_status_idx".into(),
                definition: "CREATE INDEX orders_status_idx ON public.orders (status)".into(),
                unique: false,
                primary: false,
            },
        ];
        st.triggers = vec![TriggerInfo {
            name: "trg".into(),
            definition: "CREATE TRIGGER trg BEFORE INSERT ON public.orders EXECUTE FUNCTION f()"
                .into(),
        }];
        let d = ddl(&t, &st);
        assert!(d.starts_with("create table \"public\".\"orders\" (\n"));
        assert!(d.contains("\"id\" integer generated always as identity not null"));
        assert!(d.contains("\"status\" text default 'new'::text"));
        assert!(d.contains("\"total2\" numeric generated always as ((total * 2)) stored"));
        assert!(d.contains("\"n\" integer generated by default as identity"));
        assert!(d.contains("constraint \"orders_pkey\" PRIMARY KEY (id)"));
        assert!(d.contains("CREATE INDEX orders_status_idx"));
        assert!(!d.contains("CREATE UNIQUE INDEX orders_pkey"));
        assert!(d.contains("CREATE TRIGGER trg"));
    }

    #[test]
    fn view_ddl() {
        let t = TableRef::new("public", "v");
        let mut st = empty(ObjectKind::View);
        st.view_definition = Some(" SELECT 1 AS x;\n".into());
        assert_eq!(
            ddl(&t, &st),
            "create view \"public\".\"v\" as\n SELECT 1 AS x;\n"
        );
        st.kind = ObjectKind::MaterializedView;
        assert!(ddl(&t, &st).starts_with("create materialized view"));
    }

    #[tokio::test]
    async fn load_live() {
        let Some((client, _)) = crate::connect::test_connection().await else {
            return;
        };
        client
            .batch_execute(
                "drop schema if exists pgroove_s cascade; create schema pgroove_s; \
                 create table pgroove_s.p (id int primary key); \
                 create table pgroove_s.c (id int generated always as identity primary key, \
                    pid int not null references pgroove_s.p(id), n text default 'x', \
                    check (id > 0)); \
                 comment on column pgroove_s.c.n is 'note'; \
                 create index c_n_idx on pgroove_s.c (n); \
                 create view pgroove_s.v as select id from pgroove_s.c",
            )
            .await
            .unwrap();
        let t = TableRef::new("pgroove_s", "c");
        let st = load(&client, &t).await.unwrap();
        assert_eq!(st.kind, ObjectKind::Table);
        assert_eq!(st.columns.len(), 3);
        assert_eq!(st.columns[0].identity, Some('a'));
        assert!(st.columns[1].not_null);
        assert_eq!(st.columns[2].default.as_deref(), Some("'x'::text"));
        assert_eq!(st.columns[2].comment.as_deref(), Some("note"));
        let fk = st.constraints.iter().find(|c| c.kind == 'f').unwrap();
        assert_eq!(fk.references, Some(TableRef::new("pgroove_s", "p")));
        assert_eq!(fk.columns, ["pid"], "the foreign key names its column");
        let pk = st.constraints.iter().find(|c| c.kind == 'p').unwrap();
        assert_eq!(pk.columns, ["id"], "so does the primary key");
        assert!(st.constraints.iter().any(|c| c.kind == 'c'));
        let check = st.constraints.iter().find(|c| c.kind == 'c').unwrap();
        assert_eq!(check.columns, ["id"], "a check lists what it looks at");
        assert!(st.indexes.iter().any(|i| i.name == "c_n_idx" && !i.unique));
        assert!(st.stats.total_bytes > 0);
        let d = ddl(&t, &st);
        assert!(d.contains("create table \"pgroove_s\".\"c\""));
        // The generated DDL must be runnable.
        client
            .batch_execute("drop schema pgroove_s cascade")
            .await
            .unwrap();
        client
            .batch_execute("create schema pgroove_s")
            .await
            .unwrap();
        client
            .batch_execute("create table pgroove_s.p (id int primary key)")
            .await
            .unwrap();
        client.batch_execute(&d).await.unwrap();

        let v = load(&client, &TableRef::new("pgroove_s", "v")).await;
        assert!(v.is_err(), "dropped objects report an error");
        assert!(
            load(&client, &TableRef::new("pgroove_s", "nope"))
                .await
                .unwrap_err()
                .to_string()
                .contains("no longer exists")
        );
        client
            .batch_execute("drop schema pgroove_s cascade")
            .await
            .unwrap();
    }
}
